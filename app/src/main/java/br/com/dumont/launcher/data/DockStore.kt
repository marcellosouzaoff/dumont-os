package br.com.dumont.launcher.data

import android.content.Context
import br.com.dumont.launcher.model.AppEntry

/** User-pinned shortcuts; unlike launch history, these are always kept in dock order. */
class DockStore(context: Context) {
    private val prefs = context.getSharedPreferences("dumont_dock", Context.MODE_PRIVATE)

    fun load(apps: List<AppEntry>): List<String> {
        val pinned = prefs.getString("pinned", null)
        if (pinned != null) return pinned.lineSequence().filter { it.isNotBlank() }.distinct().take(9).toList()

        // Migrates v0.5. The 8 initial Google defaults were auto-generated, not user pins.
        // Keep any customized legacy favorites rather than silently discarding user choices.
        val legacy = prefs.getString("favorites", null)
        val autogenerated = AppRules.initialDockKeys(apps.map { it.packageName to it.key })
        val result = if (legacy == null || legacy.lineSequence().filter { it.isNotBlank() }.toList() == autogenerated) {
            emptyList()
        } else {
            legacy.lineSequence().filter { it.isNotBlank() }.distinct().take(9).toList()
        }
        save(result)
        return result
    }

    fun save(keys: List<String>) {
        prefs.edit().putString("pinned", keys.distinct().take(9).joinToString("\n")).apply()
    }
}
